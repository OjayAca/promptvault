  provider_customer_id text,
  provider_payment_id text,
  provider_payment_token_id text,
  provider_recurring_plan_id text unique,
  payment_succeeded boolean not null default false,
  status text not null default 'creating' check (status in ('creating', 'pending', 'paid', 'plan_created', 'cancelled', 'failed')),
