create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text check (char_length(full_name) <= 120),
  mobile_number text check (mobile_number is null or mobile_number ~ '^\+639[0-9]{9}$'),
  role public.user_role not null default 'user',
  preferred_category public.prompt_category,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.subscriptions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  plan public.subscription_plan not null default 'Free',
  status public.subscription_status not null default 'free',
  provider text check (provider is null or provider = 'xendit'),
  provider_subscription_id text unique,
  provider_checkout_id text unique,
  provider_customer_id text,
  provider_payment_token_id text,
  provider_last_cycle_id text,
  provider_last_cycle_number integer check (provider_last_cycle_number is null or provider_last_cycle_number > 0),
  provider_event_id text,
  provider_event_created_at timestamptz,
  current_period_start timestamptz,
  current_period_end timestamptz,
  access_until timestamptz,
  grace_until timestamptz,
  cancelled_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.prompts (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 160),
  category public.prompt_category not null,
  access public.prompt_access not null default 'Free',
  status public.prompt_status not null default 'Published',
  purpose text not null check (char_length(purpose) between 1 and 500),
  prompt text not null check (char_length(prompt) between 1 and 12000),
  best_for text not null check (char_length(best_for) between 1 and 500),
  tags text[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.prompt_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  category public.prompt_category not null,
  title text not null check (char_length(title) between 3 and 160),
  details text not null check (char_length(details) between 10 and 3000),
  status public.prompt_request_status not null default 'open',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.billing_checkout_sessions (
