create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;

create or replace function public.has_active_entitlement()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.is_admin() or exists (
    select 1
    from public.subscriptions
    where user_id = (select auth.uid())
      and plan = 'Founding'
      and (
        access_until > now()
        or (status = 'past_due' and grace_until > now())
      )
  );
$$;

create or replace function public.get_prompt_catalog()
returns table (
  id bigint,
  title text,
  category public.prompt_category,
  access public.prompt_access,
  status public.prompt_status,
  purpose text,
  prompt text,
  best_for text,
  tags text[],
  created_at timestamptz,
  updated_at timestamptz
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    p.id,
    p.title,
    p.category,
    p.access,
    p.status,
    p.purpose,
    case
      when p.access = 'Free' or public.has_active_entitlement() then p.prompt
      else null
    end,
    p.best_for,
    p.tags,
    p.created_at,
    p.updated_at
  from public.prompts p
  where p.status = 'Published'
  order by p.id;
$$;

create or replace function public.admin_update_user_access(
  target_user_id uuid,
  next_role public.user_role,
  next_plan public.subscription_plan,
  next_status public.subscription_status,
  next_access_until timestamptz
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.is_admin() then
    raise exception 'Admin access required';
  end if;

  if target_user_id = (select auth.uid()) and next_role <> 'admin' then
    raise exception 'You cannot remove your own admin access';
  end if;

  if next_role <> 'admin'
    and exists (select 1 from public.profiles where id = target_user_id and role = 'admin')
    and (select count(*) from public.profiles where role = 'admin') <= 1 then
    raise exception 'At least one administrator is required';
  end if;

  update public.profiles
  set role = next_role, updated_at = now()
  where id = target_user_id;

  if not found then
    raise exception 'User profile not found';
  end if;

  insert into public.subscriptions (user_id, plan, status, access_until, updated_at)
  values (target_user_id, next_plan, next_status, next_access_until, now())
  on conflict (user_id) do update
  set plan = excluded.plan,
      status = excluded.status,
      access_until = excluded.access_until,
      updated_at = excluded.updated_at;
end;
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, email, full_name)
  values (new.id, new.email, left(new.raw_user_meta_data->>'full_name', 120))
  on conflict (id) do nothing;

  insert into public.subscriptions (user_id, plan, status)
  values (new.id, 'Free', 'free')
  on conflict (user_id) do nothing;

  return new;
end;
$$;

create or replace function public.enforce_open_prompt_request_limit()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(new.user_id::text, 0));

  if new.status in ('open', 'reviewing')
    and (
      select count(*)
      from public.prompt_requests
      where user_id = new.user_id and status in ('open', 'reviewing')
    ) >= 3 then
    raise exception 'At most three open or reviewing prompt requests are allowed';
  end if;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create trigger enforce_prompt_request_limit
before insert on public.prompt_requests
for each row execute function public.enforce_open_prompt_request_limit();

